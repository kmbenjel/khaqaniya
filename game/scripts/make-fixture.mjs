#!/usr/bin/env node
// Dev fixtures for the game until the real data files exist (never typed by hand, never deployed):
//   fixtures/khaqaniya.dev.json  <- reviews/t2/witness/ghouthani_frames.tsv (T2's careful reading of Ghouthani's slides)
//                                   + the reciter's own chapters (sources/ghouthani/video_info.json) mapped to verses by time
//   fixtures/meanings.dev.json   <- placeholder strings (M1 writes text/meanings.json)
// Usage: node scripts/make-fixture.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(GAME, '..');
const rd = (p) => readFileSync(path.join(REPO, p), 'utf8');

const rows = rd('reviews/t2/witness/ghouthani_frames.tsv').split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => l.split('\t'));
const verses = rows.map(([n, sadr, ajz]) => {
  sadr = sadr.normalize('NFC').trim(); ajz = ajz.normalize('NFC').trim();
  const toks = ajz.split(/\s+/);
  return { n: Number(n), section: '', sadr, ajz, rhymeWord: toks[toks.length - 1] };
});

// sections = the reciter's chapters; a verse belongs to the chapter its start time falls in
const info = JSON.parse(rd('sources/ghouthani/video_info.json'));
const seg = JSON.parse(rd('sources/ghouthani/segments.json'));
const chapters = info.chapters;
const sections = chapters.map((c, i) => ({ id: 's' + (i + 1), title: c.title.trim(), from: 0, to: 0, theme: '' }));
for (const v of verses) {
  const t = seg.verses.find((s) => s.n === v.n).start;
  const ci = chapters.findIndex((c) => t >= c.start_time && t < c.end_time);
  const s = sections[ci];
  v.section = s.id;
  if (!s.from) s.from = v.n;
  s.to = v.n;
}

const poem = {
  _fixture: 'DEV FIXTURE generated by game/scripts/make-fixture.mjs from reviews/t2/witness/ghouthani_frames.tsv; replace by text/khaqaniya.json',
  title: 'الْخَاقَانِيَّة',
  fullTitle: 'الْقَصِيدَةُ الْخَاقَانِيَّةُ فِي الْقُرَّاءِ وَحُسْنِ الْأَدَاءِ',
  author: 'أَبُو مُزَاحِمٍ مُوسَى بْنُ عُبَيْدِ اللَّهِ الْخَاقَانِيُّ',
  authorDeath: '325',
  metre: 'الطويل',
  rhyme: 'ر',
  basis: 'dev fixture: Ghouthani slides as read by T2',
  sections: sections.filter((s) => s.from),
  verses,
};

const meanings = {
  _fixture: 'DEV FIXTURE: placeholder strings; replace by text/meanings.json (M1)',
  verses: verses.map((v) => {
    const words = v.sadr.split(/\s+/).filter((w) => w.replace(/[ً-ٰٟ]/g, '').length >= 5).slice(0, 2);
    return {
      n: v.n,
      kid: `[fixture] kid meaning of verse ${v.n}`,
      adult: `[fixture] adult explanation of verse ${v.n}`,
      words: words.map((w, i) => ({ w, m: `[fixture] meaning ${i + 1}` })),
      lesson: `[fixture] lesson of verse ${v.n}`,
      cite: ['[fixture] source'],
    };
  }),
};

mkdirSync(path.join(GAME, 'fixtures'), { recursive: true });
writeFileSync(path.join(GAME, 'fixtures/khaqaniya.dev.json'), JSON.stringify(poem, null, 1) + '\n');
writeFileSync(path.join(GAME, 'fixtures/meanings.dev.json'), JSON.stringify(meanings, null, 1) + '\n');
console.log(`fixtures: ${verses.length} verses, ${poem.sections.length} sections (ends ${poem.sections.map((s) => s.to).join(', ')})`);
