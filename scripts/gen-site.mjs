#!/usr/bin/env node
// gen-site — generate the shatr site's content from the project's single text source.
//   text/khaqaniya.json   -> site/content/poem.txt          (one shatr per line, `## ` section titles)
//   text/meanings.json    -> site/content/bayts.json        (kid meaning, hard words, adult text behind «المزيد»)
//   audio/timings.json    -> site/content/bayts.json + site/content/audio/NNN.<ext>   (one clip per bayt)
//   text/SOURCES.md       -> credits (lines between <!-- site:credits --> and <!-- /site:credits -->)
//   site/poem.config.json + site/hosting.json -> site/content/poem.config.json (adds domain, basePath)
// Nothing is typed by hand: re-run after any correction. When text/khaqaniya.json does not exist yet it falls back
// to site/fixtures/ (clearly marked, writes site/content/FIXTURE so CI can refuse to deploy it). `--fixtures` forces that.
// Hosting switch: site/hosting.json {"base": "https://benjelloun.dev/khaqaniya"} or env KQ_BASE; the poem site is at <base>/qasida/.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = path.join(ROOT, 'site');
const OUT = path.join(SITE, 'content');
const die = (m) => { console.error('\x1b[31m✗ gen-site: ' + m + '\x1b[0m'); process.exit(1); };
const warn = (m) => console.warn('\x1b[33m⚠ gen-site: ' + m + '\x1b[0m');
const readJson = (p) => { try { return JSON.parse(readFileSync(p, 'utf8')); } catch (e) { die(`${path.relative(ROOT, p)}: ${e.message}`); } };
const nfc = (s) => String(s ?? '').normalize('NFC');
const clean = (s) => nfc(s).replace(/ـ/g, '').replace(/\s+/g, ' ').trim();   // no tatweel in the source: layouts add it

const forceFixtures = process.argv.includes('--fixtures');
const realText = path.join(ROOT, 'text/khaqaniya.json');
const fixture = forceFixtures || !existsSync(realText);
const dir = fixture ? path.join(SITE, 'fixtures') : null;
const P = {
    poem: fixture ? path.join(dir, 'khaqaniya.json') : realText,
    meanings: fixture ? path.join(dir, 'meanings.json') : path.join(ROOT, 'text/meanings.json'),
    timings: fixture ? path.join(dir, 'timings.json') : path.join(ROOT, 'audio/timings.json'),
    sources: path.join(ROOT, 'text/SOURCES.md'),
};
const audioRoot = fixture ? dir : ROOT;   // timings `file` is relative to the repo root (fixtures: to site/fixtures)
if (fixture) warn('using site/fixtures/ (NOT the poem). Do not deploy this build.');

// ── poem ───────────────────────────────────────────────────────────────────────
const poem = readJson(P.poem);
if (!Array.isArray(poem.verses) || !poem.verses.length) die('verses[] is empty');
const sections = Array.isArray(poem.sections) && poem.sections.length ? poem.sections : [{ id: '_', title: null }];
const secIds = new Set(sections.map(s => s.id));
const verses = poem.verses.slice();
for (const v of verses) {
    if (!clean(v.sadr) || !clean(v.ajz)) die(`verse ${v.n}: sadr/ajz missing`);
    if (v.section && !secIds.has(v.section)) die(`verse ${v.n}: unknown section "${v.section}"`);
    if (/ـ/.test(v.sadr + v.ajz)) warn(`verse ${v.n}: tatweel in the source, stripped`);
}
const dupN = verses.map(v => v.n).filter((n, i, a) => a.indexOf(n) !== i);
if (dupN.length) die('duplicate verse numbers: ' + [...new Set(dupN)].join(', '));

// order: by section (as listed), keeping the array order inside a section
const ordered = [];
for (const s of sections) for (const v of verses) if ((v.section || '_') === s.id || (sections.length === 1 && !v.section)) ordered.push({ v, sec: s });
if (ordered.length !== verses.length) die('some verses belong to no section');
const pos = new Map(ordered.map((o, i) => [o.v.n, i + 1]));   // verse n -> bayt position (what the engine counts)

let txt = '# GENERATED by scripts/gen-site.mjs from ' + (fixture ? 'site/fixtures/' : 'text/khaqaniya.json') + ' — do not edit.\n';
let lastSec = null;
for (const { v, sec } of ordered) {
    if (sec !== lastSec) { txt += (sections.length > 1 || sec.title ? `\n## ${clean(sec.title) || ''}\n` : ''); lastSec = sec; }
    txt += clean(v.sadr) + '\n' + clean(v.ajz) + '\n';
}

// ── meanings + audio -> bayts.json ──────────────────────────────────────────────
const byN = new Map();
const entry = (n) => { if (!pos.has(n)) { warn(`sidecar mentions verse ${n}, which is not in the poem: ignored`); return null; }
    if (!byN.has(n)) byN.set(n, { n: pos.get(n) }); return byN.get(n); };
if (existsSync(P.meanings)) {
    for (const m of readJson(P.meanings).verses || []) {
        const e = entry(m.n); if (!e) continue;
        if (m.kid && clean(m.kid)) e.kid = clean(m.kid);
        const words = (m.words || []).filter(x => x && clean(x.w) && clean(x.m)).map(x => ({ w: clean(x.w), m: clean(x.m) }));
        if (words.length) e.words = words;
        if (m.adult && clean(m.adult)) e.more = clean(m.adult);
    }
} else warn('no meanings.json yet: the site shows the text only');
let credit = { href: '' };
if (existsSync(P.timings)) {
    const t = readJson(P.timings);
    credit = (t.source && t.source) || credit;
    rmSync(path.join(OUT, 'audio'), { recursive: true, force: true });
    for (const c of t.verses || []) {
        const e = entry(c.n); if (!e || !c.file) continue;
        const src = path.join(audioRoot, c.file);
        if (!existsSync(src)) { warn(`audio for verse ${c.n}: ${c.file} not found, skipped`); continue; }
        const rel = `audio/${String(pos.get(c.n)).padStart(3, '0')}${path.extname(c.file)}`;
        mkdirSync(path.join(OUT, 'audio'), { recursive: true });
        copyFileSync(src, path.join(OUT, rel));
        e.audio = rel;
    }
} else warn('no audio/timings.json yet: no audio buttons');

// ── config + credits ────────────────────────────────────────────────────────────
const cfg = readJson(path.join(SITE, 'poem.config.json'));
const base = (process.env.KQ_BASE || readJson(path.join(SITE, 'hosting.json')).base || '').replace(/\/+$/, '');
let u; try { u = new URL(base); } catch { die(`hosting base "${base}" is not a URL (e.g. https://benjelloun.dev/khaqaniya)`); }
cfg.domain = u.host;
cfg.basePath = (u.pathname.replace(/\/+$/, '') + '/qasida/').replace(/^\/?/, '/');
const C = cfg.credits || {};
const items = [];
if (C.recitationText) items.push({ label: C.recitationLabel, text: C.recitationText, ...(credit.url && !fixture ? { href: credit.url } : {}) });
if (poem.basis && !fixture) items.push({ label: C.basisLabel, text: clean(poem.basis) });
if (existsSync(P.sources)) {
    const m = readFileSync(P.sources, 'utf8').match(/<!--\s*site:credits\s*-->([\s\S]*?)<!--\s*\/site:credits\s*-->/);
    if (m) for (const line of m[1].split('\n')) { const t = line.match(/^\s*[-*]\s+(.+)$/); if (t) items.push({ label: items.some(i => i.label === C.sourcesLabel) ? '' : C.sourcesLabel, text: clean(t[1]) }); }
    else warn('text/SOURCES.md has no <!-- site:credits --> … <!-- /site:credits --> block: no source credits on the site');
} else warn('no text/SOURCES.md yet: no source credits');
cfg.credits = { title: C.title, items };
if (fixture) cfg.title = clean(poem.title || 'نموذج');

// ── write ───────────────────────────────────────────────────────────────────────
mkdirSync(OUT, { recursive: true });
writeFileSync(path.join(OUT, 'poem.txt'), txt);
writeFileSync(path.join(OUT, 'bayts.json'), JSON.stringify({ bayts: [...byN.values()].sort((a, b) => a.n - b.n) }, null, 1) + '\n');
writeFileSync(path.join(OUT, 'poem.config.json'), JSON.stringify(cfg, null, 2) + '\n');
if (fixture) writeFileSync(path.join(OUT, 'FIXTURE'), 'built from site/fixtures, not the poem\n'); else rmSync(path.join(OUT, 'FIXTURE'), { force: true });
const withM = [...byN.values()].filter(e => e.kid).length, withA = [...byN.values()].filter(e => e.audio).length;
console.log(`\x1b[32m✓ gen-site (${fixture ? 'FIXTURES' : 'real'}): ${ordered.length} bayt(s), ${withM} meaning(s), ${withA} clip(s); ${cfg.domain}${cfg.basePath}\x1b[0m`);
